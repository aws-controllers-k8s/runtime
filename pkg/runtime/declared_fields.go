// The UnsetFieldsUnmanaged feature treats a spec field the user never set as
// not managed by the resource: when AWS reports a value for it (typically a
// server-side default), that difference does not drive an Update.
//
// A nil field alone cannot tell "never set" from "removed by the user", so the
// controller records which spec paths were set at the last successful sync in
// the services.k8s.aws/declared-fields annotation. A difference whose desired
// side is unset is dropped only when its path is NOT in that record. A path
// that is in the record was set before, so the user removed it, and the
// difference is kept: removal behaves exactly as it does without the gate.
//
// The record holds paths, never values, so its size does not depend on the
// size of the values. It is bound to metadata.uid so that a manifest copied
// with the annotation, or an object restored under a new UID, does not inherit
// another object's record. A missing or foreign record is replaced by the
// fields set right now, so the failure mode is that a removal made before the
// record existed is not seen; the filter never drops a difference for a path
// the user set.

// maxDeclaredFieldsAnnotationBytes caps the size of the record. Kubernetes
// limits the total size of an object's annotations to 256 KiB; the measured
// p90 record is ~230 bytes, so hitting this cap means something is wrong and
// we prefer not writing the record (fail-safe) over growing the object.
const maxDeclaredFieldsAnnotationBytes = 32 * 1024

// unsetMeansEmptyFieldNames is the fallback for descriptors generated by a
// code-generator without compare.unset_means_empty support: field names for
// which an unset value keeps meaning "must be empty". Tags are reconciled as a
// complete set, so a tag added out of band is still removed. Descriptors that
// implement AWSResourceDescriptorWithUnsetMeansEmpty supply the exact list
// instead (compare.unset_means_empty plus the tag field).
var unsetMeansEmptyFieldNames = map[string]struct{}{
	"tags":    {},
	"tagging": {},
	"taglist": {},
	"tagset":  {},
}

// declaredFieldsRecord is the JSON form of the declared-fields annotation.
type declaredFieldsRecord struct {
	UID    types.UID              `json:"uid"`
	Fields map[string]interface{} `json:"fields"`
}

// declaredSpecPaths returns the dotted, JSON-style paths (relative to spec)
// of every field set on the resource's spec. It descends through structs only:
// list elements and map keys are not recorded, because the generated delta
// compares lists and maps as a whole. A typed resource is walked by
// reflection; an unstructured one by walking its spec map.
func declaredSpecPaths(res acktypes.AWSResource) []string {
	if ackcompare.IsNil(res) {
		return nil
	}
	obj := res.RuntimeObject()
	if u, ok := obj.(*unstructured.Unstructured); ok {
		spec, found, _ := unstructured.NestedMap(u.Object, "spec")
		if !found {
			return nil
		}
		var paths []string
		walkUnstructured(spec, "", &paths)
		sort.Strings(paths)
		return paths
	}
	v := reflect.ValueOf(obj)
	for v.Kind() == reflect.Ptr || v.Kind() == reflect.Interface {
		if v.IsNil() {
			return nil
		}
		v = v.Elem()
	}
	if v.Kind() != reflect.Struct {
		return nil
	}
	spec := v.FieldByName("Spec")
	if !spec.IsValid() {
		return nil
	}
	var paths []string
	walkTyped(spec, "", &paths)
	sort.Strings(paths)
	return paths
}

var jsonMarshalerType = reflect.TypeOf((*json.Marshaler)(nil)).Elem()

// walkTyped appends the path of every set field reachable from v through
// structs. A field is set when it is a non-nil pointer, slice, map or
// interface, or a non-zero value of any other kind (the same rule as
// encoding/json's omitempty, except that an explicitly empty, non-nil list or
// map counts as set).
func walkTyped(v reflect.Value, prefix string, paths *[]string) {
	for v.Kind() == reflect.Ptr || v.Kind() == reflect.Interface {
		if v.IsNil() {
			return
		}
		v = v.Elem()
	}
	if v.Kind() != reflect.Struct {
		return
	}
	t := v.Type()
	for i := 0; i < t.NumField(); i++ {
		sf := t.Field(i)
		// Skip unexported fields, except embedded structs, whose exported
		// fields encoding/json promotes into the parent.
		if sf.PkgPath != "" && !(sf.Anonymous && derefType(sf.Type).Kind() == reflect.Struct) {
			continue
		}
		name, inline := jsonFieldName(sf)
		if name == "-" {
			continue
		}
		fv := v.Field(i)
		if inline {
			walkTyped(fv, prefix, paths)
			continue
		}
		if !isSetValue(fv) {
			continue
		}
		p := name
		if prefix != "" {
			p = prefix + "." + name
		}
		*paths = append(*paths, p)
		if isLeafType(fv.Type()) {
			continue
		}
		walkTyped(fv, p, paths)
	}
}

func derefType(t reflect.Type) reflect.Type {
	for t.Kind() == reflect.Ptr {
		t = t.Elem()
	}
	return t
}

// jsonFieldName returns the JSON name of a struct field and whether the field
// is an embedded struct whose fields are inlined into the parent.
func jsonFieldName(sf reflect.StructField) (string, bool) {
	tag := sf.Tag.Get("json")
	name := strings.Split(tag, ",")[0]
	if sf.Anonymous && name == "" {
		return "", true
	}
	if name == "" {
		name = sf.Name
	}
	return name, false
}

// isSetValue reports whether a field value would be present in the object's
// JSON.
func isSetValue(v reflect.Value) bool {
	switch v.Kind() {
	case reflect.Ptr, reflect.Interface, reflect.Map, reflect.Slice:
		return !v.IsNil()
	default:
		return !v.IsZero()
	}
}

// isLeafType reports whether the walk should stop at a value of type t:
// lists, maps, scalars, and types with their own JSON encoding (for example
// metav1.Time) are leaves; only plain structs are descended into.
func isLeafType(t reflect.Type) bool {
	if t.Implements(jsonMarshalerType) || reflect.PointerTo(t).Implements(jsonMarshalerType) {
		return true
	}
	for t.Kind() == reflect.Ptr {
		t = t.Elem()
		if t.Implements(jsonMarshalerType) || reflect.PointerTo(t).Implements(jsonMarshalerType) {
			return true
		}
	}
	return t.Kind() != reflect.Struct
}

// walkUnstructured is the fallback for resources backed by unstructured
// objects. It cannot tell a struct from a map, so it descends into every map.
func walkUnstructured(m map[string]interface{}, prefix string, paths *[]string) {
	for k, v := range m {
		p := k
		if prefix != "" {
			p = prefix + "." + k
		}
		*paths = append(*paths, p)
		if sub, ok := v.(map[string]interface{}); ok {
			walkUnstructured(sub, p, paths)
		}
	}
}

// encodeDeclaredFieldsRecord returns the annotation value for the supplied
// UID and paths. The encoding is deterministic (encoding/json sorts map keys),
// so an unchanged record compares equal as a string and is never rewritten.
func encodeDeclaredFieldsRecord(uid types.UID, paths []string) (string, error) {
	tree := map[string]interface{}{}
	for _, p := range paths {
		node := tree
		for _, part := range strings.Split(p, ".") {
			child, ok := node[part].(map[string]interface{})
			if !ok {
				child = map[string]interface{}{}
				node[part] = child
			}
			node = child
		}
	}
	b, err := json.Marshal(declaredFieldsRecord{UID: uid, Fields: tree})
	if err != nil {
		return "", err
	}
	return string(b), nil
}

// readDeclaredFieldsRecord returns the paths recorded on the resource. ok is
// false when there is no record, it does not parse, or it belongs to an object
// with a different UID.
func readDeclaredFieldsRecord(res acktypes.AWSResource) (paths map[string]struct{}, ok bool) {
	if ackcompare.IsNil(res) || res.MetaObject() == nil {
		return nil, false
	}
	raw, found := res.MetaObject().GetAnnotations()[ackv1alpha1.AnnotationDeclaredFields]
	if !found {
		return nil, false
	}
	var rec declaredFieldsRecord
	if err := json.Unmarshal([]byte(raw), &rec); err != nil {
		return nil, false
	}
	if rec.UID != res.MetaObject().GetUID() {
		return nil, false
	}
	paths = map[string]struct{}{}
	flattenRecordTree(rec.Fields, "", paths)
	return paths, true
}

func flattenRecordTree(tree map[string]interface{}, prefix string, out map[string]struct{}) {
	for k, v := range tree {
		p := k
		if prefix != "" {
			p = prefix + "." + k
		}
		out[p] = struct{}{}
		if sub, ok := v.(map[string]interface{}); ok {
			flattenRecordTree(sub, p, out)
		}
	}
}

// declaredFieldsForFilter returns the record the filter should use: the
// recorded paths, or, when there is no usable record, the paths set right now.
func declaredFieldsForFilter(res acktypes.AWSResource) map[string]struct{} {
	if paths, ok := readDeclaredFieldsRecord(res); ok {
		return paths
	}
	paths := map[string]struct{}{}
	for _, p := range declaredSpecPaths(res) {
		paths[p] = struct{}{}
	}
	return paths
}

// isUnsetDeltaValue reports whether a value taken from a delta Difference is
// unset: nil, or a nil pointer, slice, map or interface. An explicitly empty,
// non-nil list or map is a value the user set.
func isUnsetDeltaValue(v interface{}) bool {
	if v == nil {
		return true
	}
	rv := reflect.ValueOf(v)
	switch rv.Kind() {
	case reflect.Ptr, reflect.Interface, reflect.Map, reflect.Slice:
		return rv.IsNil()
	}
	return false
}

// filterUnsetUnmanagedDifferences removes, in place, every spec difference
// whose desired side (A) is unset and whose path the record does not contain.
// It returns the dropped paths for logging. Differences outside Spec, on tag
// fields, or on paths the user set before (a removal) are kept.
//
// unsetMeansEmpty lists the paths (Go field names, e.g. "Spec.Policy") whose
// differences are always kept; nil selects the name-based fallback.
func filterUnsetUnmanagedDifferences(
	delta *ackcompare.Delta,
	declared map[string]struct{},
	unsetMeansEmpty []string,
) []string {
	if delta == nil {
		return nil
	}
	var dropped []string
	kept := delta.Differences[:0]
	for _, diff := range delta.Differences {
		if diff != nil && isUnsetDeltaValue(diff.A) && diff.Path.Contains("Spec") &&
			!pathIsUnsetMeansEmpty(diff.Path, unsetMeansEmpty) && !pathInRecord(diff.Path, declared) {
			dropped = append(dropped, diff.Path.String())
			continue
		}
		kept = append(kept, diff)
	}
	delta.Differences = kept
	return dropped
}

func pathInRecord(p ackcompare.Path, declared map[string]struct{}) bool {
	for d := range declared {
		if p.EqualFold("Spec." + d) {
			return true
		}
	}
	return false
}

func pathIsUnsetMeansEmpty(p ackcompare.Path, unsetMeansEmpty []string) bool {
	if unsetMeansEmpty == nil {
		for name := range unsetMeansEmptyFieldNames {
			if p.ContainsFold("Spec." + name) {
				return true
			}
		}
		return false
	}
	for _, optedOut := range unsetMeansEmpty {
		// A difference at or under an opted-out field is kept.
		if p.ContainsFold(optedOut) {
			return true
		}
	}
	return false
}

// unsetMeansEmptyPaths returns the opted-out paths from the descriptor, or nil
// when the descriptor was generated without compare.unset_means_empty support.
func (r *resourceReconciler) unsetMeansEmptyPaths() []string {
	d, ok := r.rd.(acktypes.AWSResourceDescriptorWithUnsetMeansEmpty)
	if !ok {
		return nil
	}
	paths := d.UnsetMeansEmptyPaths()
	if paths == nil {
		paths = []string{}
	}
	return paths
}

// nextDeclaredPaths returns the record to store after a successful sync: the
// paths set on `declared`, plus every previously recorded path that the user
// removed but AWS still reports in `observed` (the ReadOne result from before
// any Update). Keeping such a pending removal in the record keeps its
// difference visible on the next sync, so removal behaves exactly as it does
// without the gate until AWS no longer reports the value. Without this, a
// removal that the generated Update cannot apply would be tried once and then
// silently treated as unmanaged.
func nextDeclaredPaths(declared, observed acktypes.AWSResource) []string {
	now := declaredSpecPaths(declared)
	previous, ok := readDeclaredFieldsRecord(declared)
	if !ok || ackcompare.IsNil(observed) {
		return now
	}
	set := map[string]struct{}{}
	for _, p := range now {
		set[p] = struct{}{}
	}
	for _, p := range declaredSpecPaths(observed) {
		if _, wasDeclared := previous[p]; wasDeclared {
			set[p] = struct{}{}
		}
	}
	out := make([]string, 0, len(set))
	for p := range set {
		out = append(out, p)
	}
	sort.Strings(out)
	return out
}

// ensureDeclaredFieldsRecord writes the declared-fields record onto the CR
// when it differs from the stored one. It is called once at the end of a
// successful Sync. The record only changes when the SET of declared paths
// changes (a field added or removed, not a value edited), so in steady state
// this makes no API call. Failing to write the record is logged and does not
// fail the reconcile: a missing record is the fail-safe state.
func (r *resourceReconciler) ensureDeclaredFieldsRecord(
	ctx context.Context,
	rm acktypes.AWSResourceManager,
	declared acktypes.AWSResource,
	observed acktypes.AWSResource,
	latest acktypes.AWSResource,
) acktypes.AWSResource {
	if !r.cfg.FeatureGates.IsEnabled(featuregate.UnsetFieldsUnmanaged) ||
		ackcompare.IsNil(declared) || ackcompare.IsNil(latest) || latest.MetaObject() == nil {
		return latest
	}
	rlog := ackrtlog.FromContext(ctx)
	value, err := encodeDeclaredFieldsRecord(latest.MetaObject().GetUID(), nextDeclaredPaths(declared, observed))
	if err != nil {
		rlog.Info("failed to encode declared-fields record; not writing it", "error", err.Error())
		return latest
	}
	if len(value) > maxDeclaredFieldsAnnotationBytes {
		rlog.Info("declared-fields record exceeds size cap; not writing it", "bytes", len(value))
		return latest
	}
	if latest.MetaObject().GetAnnotations()[ackv1alpha1.AnnotationDeclaredFields] == value {
		return latest
	}
	target := latest.DeepCopy()
	annotations := target.MetaObject().GetAnnotations()
	if annotations == nil {
		annotations = map[string]string{}
	}
	annotations[ackv1alpha1.AnnotationDeclaredFields] = value
	target.MetaObject().SetAnnotations(annotations)
	patched, err := r.patchResourceMetadataAndSpec(ctx, rm, latest, target)
	if err != nil {
		rlog.Info("failed to write declared-fields record", "error", err.Error())
		return latest
	}
	return patched
}
